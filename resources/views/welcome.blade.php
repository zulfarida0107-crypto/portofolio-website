function changeLanguage(lang) {
  if (!translations[lang]) return;

  // 1. Update elements with data-i18n
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (translations[lang][key]) {
      el.innerHTML = translations[lang][key];
    }
  });

  // 2. Update active pill button styling
  const btnId = document.getElementById('lang-btn-id');
  const btnEn = document.getElementById('lang-btn-en');
  if (btnId && btnEn) {
    if (lang === 'id') {
      btnId.className = 'px-2.5 py-1 rounded-full transition-all flex items-center justify-center cursor-pointer bg-primary text-on-primary shadow-xs';
      btnEn.className = 'px-2.5 py-1 rounded-full transition-all flex items-center justify-center cursor-pointer text-primary hover:bg-surface-container-high';
    } else {
      btnEn.className = 'px-2.5 py-1 rounded-full transition-all flex items-center justify-center cursor-pointer bg-primary text-on-primary shadow-xs';
      btnId.className = 'px-2.5 py-1 rounded-full transition-all flex items-center justify-center cursor-pointer text-primary hover:bg-surface-container-high';
    }
  }

  // 3. Save preference
  localStorage.setItem('portfolio_lang', lang);
  document.documentElement.lang = lang;
}

// Active Nav Link Underline on Click & Scroll Spy
function setupNavActiveState() {
  const navLinks = document.querySelectorAll('.nav-link');
  if (!navLinks.length) return;

  function setActiveLink(activeHref) {
    navLinks.forEach(link => {
      if (link.getAttribute('href') === activeHref) {
        link.classList.remove('text-on-surface-variant', 'border-transparent');
        link.classList.add('text-primary', 'font-bold', 'border-primary', 'dark:text-inverse-primary', 'dark:border-inverse-primary');
      } else {
        link.classList.remove('text-primary', 'font-bold', 'border-primary', 'dark:text-inverse-primary', 'dark:border-inverse-primary');
        link.classList.add('text-on-surface-variant', 'border-transparent');
      }
    });
  }

  // Click handler: immediately underlines the clicked item
  navLinks.forEach(link => {
    link.addEventListener('click', function() {
      setActiveLink(this.getAttribute('href'));
    });
  });

  // Scroll spy with IntersectionObserver
  const sectionIds = ['about', 'what-i-do', 'projects', 'tech-stack', 'experience', 'why-me', 'contact'];
  const sections = sectionIds.map(id => document.getElementById(id)).filter(Boolean);

  if ('IntersectionObserver' in window) {
    const observer = new IntersectionObserver((entries) => {
      entries.forEach(entry => {
        if (entry.isIntersecting) {
          setActiveLink('#' + entry.target.id);
        }
      });
    }, {
      rootMargin: '-20% 0px -60% 0px'
    });

    sections.forEach(section => observer.observe(section));
  }

  // If user scrolls back to the hero section at the top, clear underline so it is clean
  window.addEventListener('scroll', () => {
    if (window.scrollY < 200) {
      navLinks.forEach(link => {
        link.classList.remove('text-primary', 'font-bold', 'border-primary', 'dark:text-inverse-primary', 'dark:border-inverse-primary');
        link.classList.add('text-on-surface-variant', 'border-transparent');
      });
    }
  });
}

